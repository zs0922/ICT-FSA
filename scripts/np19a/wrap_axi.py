#!/usr/bin/env python3
"""Expose generated Chisel AXI ports as vendor-neutral named AXI interfaces.
No arithmetic, register or handshake transformation. Control AXI addresses
are rebased from host BAR offsets to original FSA registers at 0x8000.
Fail closed on any unexpected generated port so a missing signal is not tied away.
"""
import argparse,re,json
from pathlib import Path

def wrap(build):
    candidates=list(build.rglob('NP19AFSACore.sv'))
    if len(candidates)!=1: raise ValueError('Expected one emitted NP19AFSACore.sv')
    text=candidates[0].read_text();header=text.split('module NP19AFSACore(',1)[1].split(');',1)[0]
    header=re.sub(r'//[^\n]*','',header)
    ports=[];direction=None;width=''
    for token in header.split(','):
        token=token.strip()
        if not token:continue
        m=re.fullmatch(r'(?:(input|output|inout)\s+)?(?:wire\s+|logic\s+)?(\[[^]]+\])?\s*(\w+)',token)
        if not m:raise ValueError('Cannot parse core port '+repr(token))
        if m[1]:direction=m[1];width=m[2] or ''
        elif m[2]:width=m[2]
        name=m[3]
        if name in ('clock','reset'):continue
        n=re.fullmatch(r'(s_axi|m_axi)_0_(aw|w|b|ar|r)_(?:bits_)?(\w+)',name)
        if not n:raise ValueError('Unexpected core port '+name)
        prefix,channel,field=n.groups();external=f'{prefix}_{channel}{field}'
        ports.append(dict(direction=direction,width=width,name=name,external=external,interface=prefix,signal=(channel+field).upper()))
    declarations=['(* X_INTERFACE_INFO = "xilinx.com:signal:clock:1.0 aclk CLK", X_INTERFACE_PARAMETER = "ASSOCIATED_BUSIF s_axi:m_axi, ASSOCIATED_RESET aresetn, FREQ_HZ 70000000" *) input wire aclk',
      '(* X_INTERFACE_INFO = "xilinx.com:signal:reset:1.0 aresetn RST", X_INTERFACE_PARAMETER = "POLARITY ACTIVE_LOW" *) input wire aresetn']
    seen=set()
    for p in ports:
        attr=f'(* X_INTERFACE_INFO = "xilinx.com:interface:aximm:1.0 {p["interface"]} {p["signal"]}" *)'
        if p['interface'] not in seen:
            seen.add(p['interface']);attr+=f'\n(* X_INTERFACE_PARAMETER = "PROTOCOL AXI4, FREQ_HZ 70000000" *)'
        declarations.append(f'{attr} {p["direction"]} wire {p["width"]} {p["external"]}')
    for interface in ('s_axi','m_axi'):
        for signal in ['AWVALID','AWREADY','WVALID','WREADY','BVALID','BREADY','ARVALID','ARREADY','RVALID','RREADY','RLAST','WLAST']:
            if not any(p['interface']==interface and p['signal']==signal for p in ports):raise ValueError('Missing '+interface+signal)
    output='// Generated by scripts/np19a/wrap_axi.py. Control BAR rebase to 0x8000; other signals pass through.\nmodule fsa_axi_wrapper(\n'+',\n'.join(declarations)+'\n);\n'
    connections=['.clock(aclk)','.reset(!aresetn)']
    for p in ports:
        value=p['external']
        if p['interface']=='s_axi' and p['signal'] in ('AWADDR','ARADDR'):
            if p['width']!='[15:0]':raise ValueError('Expected original 16-bit control address')
            value="{1'b1, "+value+"[14:0]}"
        connections.append(f'.{p["name"]}({value})')
    output+='NP19AFSACore core (\n'+',\n'.join(connections)+'\n);\nendmodule\n'
    (build/'fsa_axi_wrapper.v').write_text(output)
    (build/'axi-port-map.json').write_text(json.dumps(ports,indent=2)+'\n')
if __name__=='__main__':
    p=argparse.ArgumentParser();p.add_argument('build',type=Path);a=p.parse_args();wrap(a.build)
